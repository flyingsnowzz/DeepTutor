  await expect(page.locator('.composer-input')).toHaveCSS('height', '93px')
  await expect(page.locator('.composer-input textarea')).toHaveCSS('height', '64px')
  await expect(page.locator('.composer-actions')).toHaveCSS('height', '42px')
  const tray = page.locator('.chat-mode-bar')
  expect((await tray.boundingBox())?.x).toBe(496)
  expect((await tray.boundingBox())?.y).toBe(481.25)
  expect((await tray.boundingBox())?.height).toBe(53)
