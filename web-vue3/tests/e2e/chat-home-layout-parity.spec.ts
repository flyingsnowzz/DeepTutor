test('composer tray folds by grip and keyboard without shifting the starter row', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.route('**/api/**', route => {
    const path = new URL(route.request().url()).pathname
    if (path === '/api/auth/status') return route.fulfill({ json: { enabled: false, authenticated: false, is_admin: false } })
    if (path === '/api/sessions') return route.fulfill({ json: { sessions: [] } })
    if (path === '/api/capabilities/registered') return route.fulfill({ json: [{ id: 'chat', available: true }, { id: 'ask_questions', available: true }] })
    return route.fulfill({ json: {} })
  })
  await page.goto('/chat')
  const tray = page.locator('.dt-composer-tray')
  const grip = page.locator('.dt-tray-grip')
  const startersY = () => page.locator('.dt-starters').evaluate(el => el.getBoundingClientRect().y)
  const initialY = await startersY()
  await expect(grip).toHaveAttribute('aria-expanded', 'true')
  await grip.click()
  await expect(tray).toHaveAttribute('data-folded', 'true')
  await expect(page.locator('.dt-tray-bar')).toHaveAttribute('inert', '')
  await expect.poll(() => page.evaluate(() => localStorage.getItem('deeptutor.composer-tray'))).toBe('folded')
  expect(await startersY()).toBe(initialY)
  await grip.press('ArrowDown')
  await expect(tray).not.toHaveAttribute('data-folded', 'true')
  await expect(grip).toHaveAttribute('aria-expanded', 'true')
  await expect.poll(() => page.evaluate(() => localStorage.getItem('deeptutor.composer-tray'))).toBe('open')
  expect(await startersY()).toBe(initialY)
  await page.getByRole('button', { name: '模式', exact: true }).click()
  await expect(page.getByRole('menuitem', { name: /主动提问/ })).toBeVisible()
  await page.keyboard.press('Escape')
})

