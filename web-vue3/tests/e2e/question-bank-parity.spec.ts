import { expect, test } from '@playwright/test'

test('question bank matches the legacy collection layout and mistakes tab', async ({ page }) => {
  await page.route('**/api/auth/status*', route => route.fulfill({ json: { enabled: false, authenticated: false, is_admin: false } }))
  await page.route('**/api/question-notebook/entries?*', route => route.fulfill({ json: { items: [], total: 0 } }))
  let categories = [{ id: 7, name: '函数', entry_count: 3 }]
  await page.route('**/api/question-notebook/categories?*', route => route.fulfill({ json: categories }))
  await page.route('**/api/question-notebook/categories/7?*', route => {
    if (route.request().method() === 'PUT') {
      categories = [{ ...categories[0], name: '三角函数' }]
      return route.fulfill({ json: categories[0] })
    }
    return route.continue()
  })
  await page.route('**/api/question-notebook/stats?*', route => route.fulfill({ json: { total: 0, wrong: 0, unresolved: 0, bookmarked: 0, uncategorized: 0 } }))
  await page.route('**/api/question-notebook/materials?*', route => route.fulfill({ json: [] }))
  await page.goto('/space/questions')
  await expect(page.locator('.question-page-bar')).toBeVisible()
  await expect(page.getByRole('tab', { name: /题库/ })).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByRole('tab', { name: /错题/ })).toHaveAttribute('aria-selected', 'false')
  await expect(page.locator('.question-rail')).toHaveCount(0)
  await expect(page.locator('.question-toolbar')).toBeVisible()
  await expect(page.locator('.question-scope-row').getByRole('button')).toHaveCount(4)
  await expect(page.locator('.question-empty')).toHaveCSS('min-height', '300px')
  await expect(page.locator('.question-collection-intro')).toContainText('各个学习场景的题目与自己的导入题目，在这里统一管理。')
  await expect(page.locator('.question-sort')).toHaveText('最新在前')
  await expect(page.locator('select[aria-label="成绩趋势"] option').first()).toHaveText('全部趋势')
  await expect(page.locator('.question-manager-toggle')).toHaveText('管理标签')
  await expect(page.locator('.question-scope-row')).toContainText('已标记')
  const searchBox = await page.locator('.question-search').boundingBox()
  expect(searchBox!.width).toBeGreaterThan(330)
  const searchInput = page.getByRole('searchbox', { name: '搜索题目' })
  await searchInput.fill('linear')
  await expect(searchInput).toHaveValue('linear')
  await searchInput.fill('')
  await expect(page.locator('.question-empty')).toContainText('暂无题目')
  await page.getByRole('tab', { name: /错题/ }).click()
  await expect(page).toHaveURL(/view=mistakes/)
  await expect(page.getByRole('tab', { name: /错题/ })).toHaveAttribute('aria-selected', 'true')
  await expect(page.locator('.question-collection-intro')).toContainText('复习后仍保留错题记录。标记为已解决，可以暂停这道题的每日复习。')
  await page.locator('.question-page-bar').getByRole('button', { name: '导入题目' }).click()
  await expect(page.locator('.practice-import')).toBeVisible()
  await expect(page.locator('.practice-import select')).toHaveValue('mistakes')
  await page.getByRole('button', { name: '管理标签' }).click()
  await expect(page.getByRole('textbox', { name: '分类名称' })).toBeVisible()
  await page.getByRole('button', { name: '改名' }).click()
  await page.getByRole('textbox', { name: '重命名分类' }).fill('三角函数')
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.locator('.question-category-name')).toHaveText('三角函数 3')
})
