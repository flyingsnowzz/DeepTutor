import { expect, test } from '@playwright/test'

test('sidebar account shelves tuck on workspace pages and expand on hover or selection', async ({ page }) => {
  await page.route('**/api/**', route => {
    const path = new URL(route.request().url()).pathname
    const json = body => route.fulfill({ json: body })
    if (path === '/api/auth/status') return json({ enabled: false, authenticated: false, is_admin: false })
    if (path === '/api/sessions') return json({ sessions: [] })
    if (path === '/api/personas') return json({ personas: [] })
    if (path === '/api/capabilities/registered') return json([])
    if (path === '/api/knowledge-bases/list') return json([])
    if (path === '/api/skills/list') return json({ skills: [] })
    if (path === '/api/partners') return json([])
    if (path === '/api/partner-groups') return json([])
    if (path === '/api/space/mcp/servers') return json({ servers: {} })
    if (path === '/api/notebooks') return json({ notebooks: [] })
    if (path === '/api/settings/ui') return json({ language: 'zh', response_language: 'zh', theme: 'snow' })
    if (path === '/api/settings/workspace/registrations') return json({ workspaces: [] })
    if (path === '/api/settings') return json({ ui: { response_language: 'en', enabled_optional_tools: [] } })
    if (path === '/api/settings/chat-attachments') return json({ effective: { max_file_bytes: 1000, max_total_bytes: 2000 } })
    if (path === '/api/settings/llm-options') return json({ active: null, options: [] })
    if (path === '/api/settings/page-customization') return json({ chat: { hidden_modes: [], controls: { skills: true, mcp: true, partners: true, preferences: true, voice: true }, starters: {} }, learning: { hidden_features: [] } })
    if (path === '/api/mastery-paths/topics/index') return json({ topics: [] })
    if (path === '/api/reading/workspaces/index') return json({ workspaces: [] })
    if (path === '/api/modules') return json({ modules: [] })
    if (path === '/api/task-board') return json({ workspaces: [], session_links: [] })
    if (path === '/api/task-board/events') return route.fulfill({ status: 200, contentType: 'text/event-stream', body: ': connected\n\n' })
    return json({})
  })
  await page.goto('/chat')
  await page.locator('form.composer textarea').waitFor()
  const accountTabs = page.locator('.dt-account-tabs')
  await expect(accountTabs).toHaveClass(/is-tucked/)
  await page.getByRole('tab', { name: '主页', exact: true }).focus()
  await page.keyboard.press('ArrowRight')
  await expect(page.getByRole('tab', { name: '学习', exact: true })).toHaveAttribute('aria-selected', 'true')
  await page.keyboard.press('End')
  await expect(page.getByRole('tab', { name: '个性化', exact: true })).toHaveAttribute('aria-selected', 'true')
  await page.keyboard.press('Home')
  await expect(page.getByRole('tab', { name: '主页', exact: true })).toHaveAttribute('aria-selected', 'true')
  await accountTabs.hover()
  await expect(accountTabs).not.toHaveClass(/is-tucked/)
  await page.getByRole('tab', { name: '学习', exact: true }).click()
  await expect(accountTabs).toHaveClass(/is-tucked/)
  await page.getByRole('tab', { name: '个性化', exact: true }).click()
  await expect(accountTabs).not.toHaveClass(/is-tucked/)
  await expect(page.locator('.dt-category-content')).toContainText('全部个性化')
  await page.getByRole('button', { name: '收起侧边栏' }).click()
  await expect(page.locator('aside.dt-rail')).toHaveCSS('width', '60px')
  await page.getByRole('button', { name: '搜索', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '搜索' })).toBeVisible()
  await page.keyboard.press('Escape')
  await page.getByRole('tab', { name: '学习', exact: true }).focus()
  await page.keyboard.press('ArrowRight')
  await expect(page.getByRole('tab', { name: '资料', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(page).toHaveURL(/\/space$/)
  await page.getByTitle('展开侧边栏').click()
  await page.goto('/partners')
  const partnerTab = page.getByRole('tab', { name: '伙伴', exact: true })
  await expect(partnerTab).toHaveAttribute('aria-selected', 'true')
  await expect.poll(() => partnerTab.evaluate(tab => tab.scrollWidth <= tab.clientWidth)).toBe(true)
  await expect.poll(() => partnerTab.evaluate(tab => tab.getBoundingClientRect().width)).toBe(71.1875)
  await expect(partnerTab.locator('svg')).toHaveAttribute('width', '20')
  await page.getByRole('tab', { name: '主页', exact: true }).focus()
  await page.keyboard.press('ArrowRight')
  await expect(page.getByRole('tab', { name: '学习', exact: true })).toHaveAttribute('aria-selected', 'true')
  await page.goto('/partners')
})
