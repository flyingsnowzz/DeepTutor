import { expect, test } from '@playwright/test'

test('general settings header, rows and selects match the React geometry', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.route('**/api/auth/status*', route => route.fulfill({ json: { enabled: false, authenticated: false, is_admin: true } }))
  await page.route('**/api/settings?*', route => route.fulfill({ json: { catalog: {}, ui: { theme: 'snow', language: 'zh', response_language: 'zh' } } }))
  await page.route('**/api/settings/draft?*', route => route.fulfill({ json: { draft: null } }))
  await page.goto('/settings/general')

  const h1 = page.locator('.legacy-settings-page-header h1')
  await expect(h1).toHaveCSS('font-size', '32px')
  await expect(h1).toHaveCSS('font-weight', '700')
  await expect(h1).toHaveCSS('line-height', '38.4px')
  const intro = page.locator('.legacy-settings-page-header p')
  await expect(intro).toHaveCSS('font-size', '14px')
  await expect(intro).toHaveCSS('line-height', '22.4px')
  await expect(intro).toHaveCSS('margin-top', '8px')

  const firstRow = page.locator('.legacy-setting-row').first()
  await expect(firstRow.locator('p')).toHaveCSS('line-height', '21.125px')
  const select = firstRow.locator('select')
  await expect(select).toHaveCSS('padding-top', '10px')
  await expect(select).toHaveCSS('padding-bottom', '10px')
  await expect(select).toHaveCSS('line-height', '20px')
  const h1Box = await h1.boundingBox()
  const selectBox = await select.boundingBox()
  expect(h1Box?.x).toBe(290)
  expect(selectBox?.x).toBe(1198)
  const sections = page.locator('.legacy-setting-section')
  await expect(sections).toHaveCount(4)
  await expect(sections.nth(0)).toHaveCSS('height', '208.75px')
  await expect(sections.nth(1)).toHaveCSS('height', '121.625px')
  await expect(sections.nth(2)).toHaveCSS('height', '367.5px')
  await expect(sections.nth(3)).toHaveCSS('height', '292.125px')
  const heading = sections.nth(0).locator('h2')
  expect((await heading.boundingBox())?.y).toBeCloseTo(128.78125, 1)
  await expect(page.locator('.legacy-setting-optional-links a p').first()).toHaveCSS('line-height', '19.5px')
})
