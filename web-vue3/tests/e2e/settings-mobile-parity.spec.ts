import { expect, test } from '@playwright/test'

test('mobile settings opens a legacy drawer with backdrop and closes on navigation', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.route('**/api/auth/status*', route => route.fulfill({ json: { enabled: false, authenticated: false } }))
  await page.route('**/api/settings**', route => route.fulfill({ json: { ui: { language: 'zh-CN', response_language: 'zh-CN', layout: 'classic' }, draft: null } }))
  await page.route('**/api/capabilities/registered*', route => route.fulfill({ json: [] }))
  await page.goto('/settings/general')
  await expect(page.locator('.legacy-settings-nav')).not.toBeVisible()
  const open = page.getByRole('button', { name: '设置分区' })
  await expect(open).toHaveAttribute('aria-expanded', 'false')
  await open.click()
  await expect(open).toHaveAttribute('aria-expanded', 'true')
  await expect(page.locator('.legacy-settings-nav.mobile-open')).toBeVisible()
  await expect(page.locator('.legacy-settings-nav-backdrop')).toBeVisible()
  await page.getByRole('searchbox', { name: '搜索设置' }).fill('外观')
  await page.getByRole('link', { name: /外观/ }).click()
  await page.waitForLoadState('networkidle').catch(() => undefined)
  await expect(page).toHaveURL(/\/settings\/appearance/)
  await expect(page.getByRole('button', { name: '设置分区' })).toHaveAttribute('aria-expanded', 'false')
  await open.click()
  await page.locator('.legacy-settings-nav-backdrop').click({ position: { x: 380, y: 24 } })
  await expect(page.getByRole('button', { name: '设置分区' })).toHaveAttribute('aria-expanded', 'false')
})
