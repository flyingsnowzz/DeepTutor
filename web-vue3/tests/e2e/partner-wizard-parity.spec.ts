import { expect, test } from '@playwright/test'

test('partner identity step matches the legacy face editor and continues to soul', async ({ page }) => {
  await page.route('**/api/auth/status*', route => route.fulfill({ json: { enabled: false, authenticated: false, is_admin: false } }))
  await page.route('**/api/partners/soul-sources?*', route => route.fulfill({ json: { library: [{ id: 'learning', name: 'Learning Companion', content: '# Soul\nLearning companion' }], personas: [{ name: 'Coach', description: 'Coach persona', content: '# Persona\nCoach' }] } }))
  await page.route('**/api/settings/llm-options?*', route => route.fulfill({ json: { active: { profile_id: 'p1', model_id: 'm1' }, options: [{ profile_id: 'p1', model_id: 'm1', profile_name: 'Local', model_name: 'Qwen', provider: 'ollama', provider_label: 'Ollama', context_window: 131072 }] } }))
  await page.route('**/api/partners/tool-options?*', route => route.fulfill({ json: { tools: [{ name: 'brainstorm', description: 'Explore ideas' }], builtin_tools: [{ name: 'rag', description: 'Read knowledge' }], mcp_tools: [{ name: 'mcp_demo', description: 'MCP demo' }] } }))
  await page.route('**/api/settings/workspace/registrations?*', route => route.fulfill({ json: { workspaces: [] } }))
  await page.route('**/api/knowledge-bases/list?*', route => route.fulfill({ json: [{ name: 'kb1' }] }))
  await page.route('**/api/skills/list?*', route => route.fulfill({ json: { skills: [{ name: 'research' }] } }))
  await page.route('**/api/notebooks?*', route => route.fulfill({ json: { notebooks: [] } }))
  await page.goto('/partners/new')
  await expect(page.getByRole('heading', { name: '这个伙伴是谁？' })).toBeVisible()
  await expect(page.getByRole('heading', { name: '这个伙伴是谁？' })).toHaveCSS('font-weight', '700')
  await expect(page.getByRole('heading', { name: '这个伙伴是谁？' })).toHaveCSS('line-height', '38.4px')
  await expect(page.getByText('先取个名字、选个形象——其余以后都能改。', { exact: true })).toHaveCSS('font-size', '14px')
  await expect(page.locator('.partner-create-page-bar')).toHaveCSS('height', '52px')
  await expect(page.locator('.partner-upload-button svg')).toHaveAttribute('width', '14')
  await expect(page.locator('.partner-upload-button')).toHaveCSS('font-size', '13px')
  await expect(page.locator('.partner-upload-button')).toHaveCSS('display', 'flex')
  await expect(page.locator('.partner-emoji-choice').first()).toHaveCSS('border-radius', '50%')
  await expect(page.locator('.partner-emoji-choice').first()).toHaveCSS('background-color', 'rgba(0, 0, 0, 0)')
  await expect(page.locator('.partner-emoji-choice')).toHaveCount(24)
  await expect(page.locator('.partner-face-colors .group-color')).toHaveCount(8)
  await expect(page.getByLabel('回复语言')).toHaveValue('')
  await expect(page.locator('.partner-identity-fields')).toHaveCSS('max-width', '672px')
  await expect(page.locator('.partner-wizard-form')).toHaveCSS('max-width', 'none')
  await page.getByLabel('名称', { exact: true }).fill('Ada')
  await page.getByRole('button', { name: '下一步', exact: true }).click()
  await expect(page.getByRole('heading', { name: '赋予它灵魂' })).toBeVisible()
  await expect(page.getByText('它是谁。可以从模板开始、克隆一个聊天 Persona，或亲手撰写。', { exact: true })).toBeVisible()
  await expect(page.locator('.partner-wizard-steps li').nth(1)).toHaveClass(/active/)
  await expect(page.getByRole('tab', { name: '灵魂库' })).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByRole('button', { name: 'Learning Companion' })).toHaveClass(/selected/)
  await expect(page.getByLabel('SOUL.md 编辑')).toHaveValue(/# Soul/)
  await page.getByRole('button', { name: '预览' }).click()
  await expect(page.locator('.soul-preview')).toContainText('Learning companion')
  await page.getByRole('tab', { name: '克隆 Persona' }).click()
  await page.getByRole('button', { name: 'Coach' }).click()
  await expect(page.getByLabel('SOUL.md 编辑')).toHaveValue(/# Persona/)
  await page.getByRole('tab', { name: '自己撰写' }).click()
  await page.getByLabel('SOUL.md 编辑').fill('# Custom soul')
  await page.getByRole('button', { name: '下一步', exact: true }).click()
  await expect(page.getByRole('heading', { name: '塑造它的心智' })).toBeVisible()
  await expect(page.getByText('它思考用的模型，以及允许使用的工具。', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: /系统默认/ })).toHaveClass(/selected/)
  const modelRow = page.locator('.partner-model-picker .partner-model-row').nth(1)
  await modelRow.click()
  await expect(modelRow).toHaveClass(/selected/)
  await page.locator('.partner-model-select > button').click()
  await expect(page.getByRole('option', { name: /Qwen/ })).toBeVisible()
  await page.getByRole('option', { name: /Qwen/ }).click()
  await expect(page.locator('.partner-model-select')).toContainText('Qwen')
  await expect(page.locator('.partner-tool-picker')).toContainText('系统工具')
  await expect(page.locator('.partner-tool-picker')).toContainText('内置工具')
  await expect(page.locator('.partner-tool-picker')).toContainText('MCP 工具')
  await expect(page.getByRole('checkbox', { name: /brainstorm/ })).toBeChecked()
  await expect(page.locator('.partner-tool-grid>label').first()).toHaveCSS('display', 'flex')
  await page.getByRole('button', { name: '下一步', exact: true }).click()
  await expect(page.getByRole('heading', { name: '交给它一些知识' })).toBeVisible()
  await expect(page.locator('.partner-workspace-picker>label')).toHaveCSS('display', 'flex')
  const kbChip = page.locator('.partner-asset-chips').getByRole('button', { name: 'kb1', exact: true })
  await expect(kbChip).not.toHaveClass(/selected/)
  await kbChip.click()
  await expect(kbChip).toHaveClass(/selected/)
  await kbChip.click()
  await expect(kbChip).not.toHaveClass(/selected/)
  await kbChip.click()
  await page.getByRole('button', { name: '下一步', exact: true }).click()
  await expect(page.getByRole('heading', { name: '准备好见到 Ada 了吗？' })).toBeVisible()
  await expect(page.locator('.partner-review-list')).toContainText('Local · Qwen')
  await expect(page.locator('.partner-review-list')).toContainText('1 系统工具')
  await expect(page.locator('.partner-review-list')).toContainText('将复制 2 项')
  await expect(page.getByRole('button', { name: '创建并启动' }).locator('svg')).toHaveAttribute('width', '15')
})
