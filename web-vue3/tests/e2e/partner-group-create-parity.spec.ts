import { expect, test } from '@playwright/test'

test('group creation uses the legacy standalone editor instead of the partner wizard', async ({ page }) => {
  await page.route('**/api/auth/status*', route => route.fulfill({ json: { enabled: false, authenticated: false, is_admin: false } }))
  await page.route(/\/api\/partners(?:\?.*)?$/, route => route.fulfill({ json: [] }))
  await page.route(/\/api\/partner-groups(?:\?.*)?$/, route => route.fulfill({ json: [] }))
  await page.route('**/api/partner-groups/discussion-modes*', route => route.fulfill({ json: [{ name: 'panel_parallel', label: '', description: '' }, { name: 'sequential', label: '', description: '' }, { name: 'debate', label: '', description: '' }] }))
  await page.goto('/partners/groups/new')
  await expect(page.getByRole('heading', { name: '创建伙伴群组' })).toBeVisible()
  await expect(page.locator('.partner-wizard-steps')).toHaveCount(0)
  await expect(page.locator('.group-create-preview')).toContainText('未命名群组')
  await expect(page.locator('.group-create-preview')).toContainText('还需再选 2 位伙伴')
  await expect(page.getByLabel('表情符号')).toHaveValue('👥')
  await expect(page.getByPlaceholder('群组名称')).toBeVisible()
  await expect(page.getByPlaceholder('这个群组要帮助你学习或决定什么？')).toBeVisible()
  await expect(page.locator('.group-color-row button')).toHaveCount(8)
  await expect(page.locator('.group-section-heading')).toContainText('已选择 0 项')
  await expect(page.locator('.group-members-empty')).toContainText('群组至少需要两位伙伴，先再创建一位。')
  await expect(page.locator('.group-mode-card')).toHaveCount(3)
  await expect(page.locator('.group-mode-card').first()).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('.group-mode-card').first()).toContainText('最快')
  await expect(page.locator('.group-mode-card').nth(1)).toContainText('较慢 · 需要依次等待')
  await expect(page.locator('.group-mode-card').nth(2)).toContainText('两轮 · 等待约翻倍')
  await expect(page.locator('.group-mode-card').first().locator('.group-mode-radio svg')).toHaveAttribute('width', '10')
  await expect(page.getByRole('button', { name: /创建群组/ })).toBeDisabled()
})
